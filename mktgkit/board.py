"""Write a self-contained accessible review board."""

from html import escape

from .errors import MktgError
from .workspace import atomic_write, scoped

MARKER = "<!-- generated by mktgkit queue render -->"


def write(root, name, items, entries):
    path = scoped(root, name)
    if path.suffix.lower() != ".html":
        raise MktgError("use an .html file for the review board")
    if path.exists() and MARKER not in path.read_text(encoding="utf-8")[:120]:
        raise MktgError("this output contains an existing file", fix="Choose a new .html path.")
    lines = [
        "<!doctype html>",
        MARKER,
        '<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">',
        "<title>Marketing review queue</title><style>",
        ":root{color-scheme:light dark}body{max-width:54rem;margin:auto;padding:2rem 1rem;font:1rem/1.55 system-ui}",
        "article{border-top:1px solid GrayText;padding-block:1rem}h2{margin:.25rem 0}.draft{white-space:pre-wrap;overflow-wrap:anywhere}",
        "@media print{details>div{display:block!important}}</style></head><body><main><h1>Marketing review queue</h1>",
    ]
    for item in items:
        latest = next((e for e in reversed(entries) if e.get("item") == item.id), {})
        fields = item.fields
        lines.extend(
            [
                "<article><small>"
                + escape(item.id + " · " + fields["priority"] + " priority · " + item.status)
                + "</small>",
                "<h2>" + escape(fields["title"]) + "</h2>",
                "<p>" + escape(fields["channel"] + " · " + fields["action"]) + "</p>",
                "<p>Last event: "
                + escape(
                    str(latest.get("event", "unknown")).replace("_", " ")
                    + " by "
                    + str(latest.get("by", "unknown"))
                )
                + "</p>",
                '<details><summary>Read draft</summary><div class="draft">'
                + escape(item.body)
                + "</div></details></article>",
            ]
        )
    if not items:
        lines.append("<p>Queue is empty.</p>")
    lines.append("</main></body></html>")
    path.parent.mkdir(parents=True, exist_ok=True)
    atomic_write(path, "\n".join(lines) + "\n")
